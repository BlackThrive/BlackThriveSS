test_that("a force's ratio trend carries every year, group and coverage flag", {
  met <- btg_get_data("force_ethnicity_year", force = "metropolitan")
  p <- btg_plot_trend(met)
  expect_s3_class(p, "ggplot")
  expect_silent(ggplot2::ggplot_build(p))
  d <- btg_figure_data(p)
  expect_equal(nrow(d), 9 * 4)
  expect_setequal(unique(d$series), c("Asian", "Black", "Mixed", "Other"))
  expect_equal(d$value[d$series == "Black" & d$period == 2025],
               met$data$ratio[met$data$group == "Black" & met$data$year == 2025])
  expect_true(all(is.finite(d$lower[d$series == "Black"])))
  expect_false(any(d$complete[d$period == 2026]))
  expect_equal(unique(d$months_in_source[d$period == 2026]), 7L)
  expect_true(all(d$complete[d$period %in% 2018:2025]))
  expect_match(p$labels$subtitle, "2026")
  expect_match(p$labels$title, "Metropolitan Police")
  rate <- btg_plot_trend(met, measure = "rate", highlight = "Black")
  expect_silent(ggplot2::ggplot_build(rate))
  r <- btg_figure_data(rate)
  expect_true("White" %in% r$series)
  expect_equal(nrow(r), 9 * 5)
  expect_true(all(is.na(r$lower)))
  gm <- btg_get_data("force_ethnicity_year", force = "greater-manchester", groups = "Black")
  g <- btg_figure_data(btg_plot_trend(gm))
  expect_true(is.na(g$value[g$period == 2025]))
  expect_false(g$complete[g$period == 2025])
  view <- attr(p, "btg_view")
  expect_equal(view$schema_version, 3L)
  expect_equal(view$chart, "trend")
  expect_equal(view$settings$measure, "ratio")
  expect_equal(view$selection$force, "metropolitan")
})

test_that("national, hit-rate, Section 60 and council trends draw their measures", {
  m <- btg_get_data("national_month_ethnicity")
  share <- btg_plot_trend(m, measure = "share")
  expect_silent(ggplot2::ggplot_build(share))
  s <- btg_figure_data(share)
