test_that("year-on-year change matches a hand calculation and reports coverage", {
  y <- btg_get_data("force_ethnicity_year", force = "metropolitan", groups = "Black")
  ch <- btg_change(y)
  expect_equal(nrow(ch), 1)
  expect_equal(ch$year_from, 2024L)
  expect_equal(ch$year_to, 2025L)
  a <- y$data[y$data$year == 2024, ]
  b <- y$data[y$data$year == 2025, ]
  expect_equal(ch$change, b$ratio / a$ratio)
  se <- sqrt(1 / a$group_stops + 1 / a$white_stops + 1 / b$group_stops + 1 / b$white_stops)
  expect_equal(ch$change_lower, exp(log(ch$change) - qnorm(0.975) * se))
  expect_equal(ch$change_upper, exp(log(ch$change) + qnorm(0.975) * se))
  expect_true(ch$change_direction %in% c("higher", "lower", "unclear"))
  expect_true(ch$comparable_coverage)
  expect_equal(ch$coverage_to, "all_months_supplied")
  all_forces <- btg_change(btg_get_data("force_ethnicity_year"), from = 2023, to = 2024)
  expect_equal(nrow(all_forces), 44 * 4)
  expect_true(all(all_forces$year_from == 2023 & all_forces$year_to == 2024))
  expect_true(all(is.na(all_forces$change_direction[!is.finite(all_forces$change)])))
  gm <- all_forces[all_forces$force == "greater-manchester", ]
  expect_true(all(gm$comparable_coverage == (gm$coverage_from %in% c("all_months_supplied", "unverified") &
                                                 gm$coverage_to %in% c("all_months_supplied", "unverified"))))
  partial <- btg_change(btg_get_data("force_ethnicity_year", force = "metropolitan"), from = 2025, to = 2026)
  expect_false(any(partial$comparable_coverage))
  expect_equal(unique(partial$months_in_source_to), 7L)
  council <- btg_change(btg_get_data("council_ethnicity_year", council = "E09000022"))
  expect_equal(nrow(council), 4)
  expect_true(all(council$comparable_coverage))
  expect_error(btg_change(y, from = 2025, to = 2025), "must differ")
  expect_error(btg_change(y, from = 2017), "calendar years")
  expect_error(btg_change(btg_get_data()), "compares years")
})

test_that("the change chart shows the largest changes with intervals and views", {
  y <- btg_get_data("force_ethnicity_year")
  p <- btg_plot_change(y)
  expect_s3_class(p, "ggplot")
  expect_silent(ggplot2::ggplot_build(p))
  d <- btg_figure_data(p)
  expect_equal(nrow(d), 10)
  expect_true(all(d$group == "Black" & d$year_from == 2024 & d$year_to == 2025))
  expect_true(all(diff(abs(log(d$change))) <= 1e-12))
  inc <- btg_figure_data(btg_plot_change(y, order = "increase", n = 5))
  expect_true(all(diff(inc$change) <= 1e-12) && all(inc$change > 1))
  dec <- btg_figure_data(btg_plot_change(y, from = 2023, to = 2025, group = "Asian", order = "decrease", n = 5))
  expect_true(all(diff(dec$change) >= -1e-12) && all(dec$change < 1))
  expect_match(p$labels$subtitle, "exclude no change")
  expect_error(btg_plot_change(y, group = "White"), "group must be")
  expect_error(btg_plot_change(y, order = "sideways"), "order must be")
  expect_error(btg_plot_change(btg_get_data("council_ethnicity_year")), "force_ethnicity_year")
  expect_error(btg_plot_change(y, n = 0), "integer")
})

test_that("trend and change views save and replay through schema 3", {
  met <- btg_get_data("force_ethnicity_year", force = "metropolitan", years = 2020:2025)
  path <- tempfile(fileext = ".json")
  on.exit(unlink(path))
  p <- btg_plot_trend(met, measure = "rate", highlight = "Black")
  btg_save_view(p, path)
  replay <- btg_from_view(path)
  expect_identical(btg_figure_data(replay), btg_figure_data(p))
  expect_identical(attr(replay, "btg_view"), attr(p, "btg_view"))
  saved <- jsonlite::read_json(path, simplifyVector = TRUE)
  expect_equal(saved$schema_version, 3)
  expect_equal(saved$selection$years, 2020:2025)
  q <- btg_plot_change(btg_get_data("force_ethnicity_year"), from = 2022, to = 2024, group = "Mixed", n = 7, order = "increase")
  btg_save_view(q, path, overwrite = TRUE)
  expect_identical(btg_figure_data(btg_from_view(path)), btg_figure_data(q))
  n <- btg_plot_trend(btg_get_data("national_month_ethnicity", groups = c("Black", "White")), measure = "share")
  btg_save_view(n, path, overwrite = TRUE)
  expect_identical(btg_figure_data(btg_from_view(path)), btg_figure_data(n))
  bad <- attr(p, "btg_view")
  bad$settings$measure <- "stops"
  jsonlite::write_json(bad, path, auto_unbox = TRUE)
  expect_error(btg_from_view(path), "measure must be")
  bad <- attr(p, "btg_view")
  bad$settings$code <- "stop('never')"
  jsonlite::write_json(bad, path, auto_unbox = TRUE)
  expect_error(btg_from_view(path), "settings")
  bad <- attr(p, "btg_view")
  bad$selection$dataset <- "private"
  jsonlite::write_json(bad, path, auto_unbox = TRUE)
  expect_error(btg_from_view(path), "selection")
  bad <- attr(p, "btg_view")
  bad$chart <- "force_disparity_ranking"
  jsonlite::write_json(bad, path, auto_unbox = TRUE)
  expect_error(btg_from_view(path), "chart")
  bad <- attr(p, "btg_view")
  bad$data_sha256 <- "wrong"
  jsonlite::write_json(bad, path, auto_unbox = TRUE)
  expect_error(btg_from_view(path), "checksums")
})
